CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email VARCHAR(255) NOT NULL UNIQUE,
                       password_hash VARCHAR(255) NOT NULL,
                       role VARCHAR(20) NOT NULL,
                       enabled BOOLEAN NOT NULL DEFAULT TRUE,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT chk_users_role
                           CHECK (role IN ('USER', 'ADMIN'))
);


CREATE TABLE movies (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        tmdb_id BIGINT NOT NULL UNIQUE,
                        title VARCHAR(255) NOT NULL,
                        original_title VARCHAR(255),
                        overview TEXT,
                        runtime INTEGER,
                        release_date DATE,
                        poster_path VARCHAR(500),
                        backdrop_path VARCHAR(500),
                        visible BOOLEAN NOT NULL DEFAULT TRUE,
                        last_synced_at TIMESTAMPTZ,

                        CONSTRAINT chk_movies_runtime
                            CHECK (runtime IS NULL OR runtime > 0)
);


CREATE TABLE halls (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(255) NOT NULL UNIQUE
);


CREATE TABLE seats (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       hall_id BIGINT NOT NULL,
                       row_label VARCHAR(20) NOT NULL,
                       number INTEGER NOT NULL,
                       active BOOLEAN NOT NULL DEFAULT TRUE,

                       CONSTRAINT fk_seats_hall
                           FOREIGN KEY (hall_id)
                               REFERENCES halls(id)
                               ON DELETE CASCADE,

                       CONSTRAINT uq_seat_in_hall
                           UNIQUE (hall_id, row_label, number),

                       CONSTRAINT chk_seat_number
                           CHECK (number > 0)
);


CREATE TABLE screenings (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            movie_id BIGINT NOT NULL,
                            hall_id BIGINT NOT NULL,
                            start_at TIMESTAMPTZ NOT NULL,
                            end_at TIMESTAMPTZ NOT NULL,
                            status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',

                            CONSTRAINT fk_screenings_movie
                                FOREIGN KEY (movie_id)
                                    REFERENCES movies(id),

                            CONSTRAINT fk_screenings_hall
                                FOREIGN KEY (hall_id)
                                    REFERENCES halls(id),

                            CONSTRAINT chk_screening_time
                                CHECK (end_at > start_at),

                            CONSTRAINT chk_screening_status
                                CHECK (status IN ('SCHEDULED', 'CANCELLED'))
);


CREATE TABLE screening_seats (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 screening_id BIGINT NOT NULL,
                                 seat_id BIGINT NOT NULL,

                                 CONSTRAINT fk_screening_seats_screening
                                     FOREIGN KEY (screening_id)
                                         REFERENCES screenings(id)
                                         ON DELETE CASCADE,

                                 CONSTRAINT fk_screening_seats_seat
                                     FOREIGN KEY (seat_id)
                                         REFERENCES seats(id),

                                 CONSTRAINT uq_screening_seat
                                     UNIQUE (screening_id, seat_id)
);


CREATE TABLE reservations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              user_id BIGINT NOT NULL,
                              screening_id BIGINT NOT NULL,
                              screening_seat_id BIGINT NOT NULL,
                              status VARCHAR(20) NOT NULL,
                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              expires_at TIMESTAMPTZ,
                              confirmed_at TIMESTAMPTZ,
                              cancelled_at TIMESTAMPTZ,

                              CONSTRAINT fk_reservations_user
                                  FOREIGN KEY (user_id)
                                      REFERENCES users(id),

                              CONSTRAINT fk_reservations_screening
                                  FOREIGN KEY (screening_id)
                                      REFERENCES screenings(id),

                              CONSTRAINT fk_reservations_screening_seat
                                  FOREIGN KEY (screening_seat_id)
                                      REFERENCES screening_seats(id),

                              CONSTRAINT chk_reservation_status
                                  CHECK (status IN ('HELD', 'CONFIRMED', 'CANCELLED', 'EXPIRED'))
);


CREATE UNIQUE INDEX uq_active_reservation_seat
    ON reservations(screening_seat_id)
    WHERE status IN ('HELD', 'CONFIRMED');


CREATE UNIQUE INDEX uq_active_user_screening
    ON reservations(user_id, screening_id)
    WHERE status IN ('HELD', 'CONFIRMED');


CREATE INDEX idx_reservations_user
    ON reservations(user_id);


CREATE INDEX idx_reservations_screening
    ON reservations(screening_id);


CREATE TABLE notifications (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               user_id BIGINT NOT NULL,
                               type VARCHAR(50) NOT NULL,
                               message TEXT NOT NULL,
                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               read_at TIMESTAMPTZ,

                               CONSTRAINT fk_notifications_user
                                   FOREIGN KEY (user_id)
                                       REFERENCES users(id)
);